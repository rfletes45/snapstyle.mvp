const WORD_PACKS: Record<WordPack, string[]> = {
  classic: CLASSIC_WORDS,
  easy: EASY_WORDS,
  hard: HARD_WORDS,
};

/**
 * Select N unique random words from the given pack.
 * Uses Fisher-Yates partial shuffle for efficiency.
 */
export function selectWords(pack: WordPack, count: number): string[] {
  const source = WORD_PACKS[pack];
  if (count > source.length) {
    throw new Error(
      `Dead Drop: requested ${count} words but pack "${pack}" only has ${source.length}.`,
    );
  }
  // Copy and partial shuffle
  const arr = [...source];
  for (let i = 0; i < count; i++) {
    const j = i + Math.floor(Math.random() * (arr.length - i));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr.slice(0, count);
}

export function getPackSize(pack: WordPack): number {
  return WORD_PACKS[pack].length;
}
